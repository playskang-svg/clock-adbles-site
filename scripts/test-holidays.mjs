// 공휴일 계산 검증: 공식 월력요항·보도로 확인된 날짜와 비교한다.
import assert from "node:assert/strict";
import { computeYear } from "../src/js/holidays-compute.js";

const dates = (y) => computeYear(y).filter((h) => h.date.startsWith(`${y}-`)).map((h) => h.date);
const has = (y, d, name) => {
  const h = computeYear(y).find((x) => x.date === d);
  assert.ok(h, `${d} 누락`);
  if (name) assert.ok(h.name.includes(name), `${d} 이름 ${h.name} ≠ ${name}`);
};
const lacks = (y, d) => assert.ok(!computeYear(y).some((x) => x.date === d), `${d} 는 공휴일이 아니어야 함`);

// 2024
has(2024, "2024-02-12", "설날 대체공휴일"); has(2024, "2024-05-06", "어린이날 대체공휴일");
has(2024, "2024-04-10", "선거"); has(2024, "2024-10-01", "임시"); has(2024, "2024-09-17", "추석"); lacks(2024, "2024-09-19");
// 2025
has(2025, "2025-01-27", "임시"); has(2025, "2025-01-29", "설날"); has(2025, "2025-03-03", "삼일절 대체공휴일");
has(2025, "2025-05-05", "부처님오신날"); has(2025, "2025-05-06", "대체공휴일"); has(2025, "2025-06-03", "대통령선거");
has(2025, "2025-10-06", "추석"); has(2025, "2025-10-08", "추석 대체공휴일");
lacks(2025, "2025-05-01"); lacks(2025, "2025-07-17"); // 노동절·제헌절은 2026년부터
// 2026 (우주항공청 월력요항 + 2026-05-11 시행 규정)
has(2026, "2026-02-17", "설날"); has(2026, "2026-03-02", "삼일절 대체공휴일"); has(2026, "2026-05-01", "노동절");
has(2026, "2026-05-24", "부처님오신날"); has(2026, "2026-05-25", "부처님오신날 대체공휴일"); has(2026, "2026-06-03", "지방선거");
has(2026, "2026-07-17", "제헌절"); has(2026, "2026-08-17", "광복절 대체공휴일"); has(2026, "2026-09-25", "추석");
has(2026, "2026-10-05", "개천절 대체공휴일"); has(2026, "2026-12-25", "성탄");
lacks(2026, "2026-06-08"); lacks(2026, "2026-09-28"); lacks(2026, "2026-05-04");
// 2026 월력요항: 일요일 제외 공휴일 70일(+노동절·제헌절 2일) → 일요일과 겹치지 않는 공휴일 수 검증
const nonSun = (y) => computeYear(y).filter((h) => h.date.startsWith(`${y}-`) && new Date(h.date + "T00:00:00Z").getUTCDay() !== 0).length;
assert.equal(nonSun(2026) + 52, 72, "2026 공휴일(일요일 포함 연간 합) 72일");
// 2027 월력요항(2026-06-29 발표): 일요일과 겹치지 않는 공휴일 + 일요일 52 → 72일, 3일 이상 연휴 구간
for (const [d, n] of [["2027-02-06", "설날"], ["2027-02-08", "설날"], ["2027-02-09", "설날 대체공휴일"], ["2027-05-03", "노동절 대체공휴일"],
  ["2027-07-19", "제헌절 대체공휴일"], ["2027-08-16", "광복절 대체공휴일"], ["2027-10-04", "개천절 대체공휴일"],
  ["2027-10-11", "한글날 대체공휴일"], ["2027-12-27", "성탄 대체공휴일".replace("성탄", "기독탄신일(성탄절)")]]) has(2027, d, n.replace("성탄 대체공휴일", "대체공휴일"));
assert.equal(nonSun(2027) + 52, 72, "2027 공휴일 72일");
lacks(2027, "2027-06-07"); lacks(2027, "2027-09-17"); // 현충일 대체 없음, 추석(9/14~16) 대체 없음
// 2028 (예상): 추석 연휴(10/2~4)가 개천절(10/3)과 겹침 → 대체공휴일 1일
has(2028, "2028-10-03", "추석"); has(2028, "2028-10-05", "대체공휴일");
console.log("holidays OK", [2024, 2025, 2026, 2027, 2028].map((y) => `${y}:${dates(y).length}`).join(" "));
